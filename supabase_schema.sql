-- Helper function to check if current user is admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND is_admin = TRUE
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 1. Profiles RLS
CREATE POLICY "Public profiles are readable by authenticated users"
ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can update own profile"
ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- 2. Members RLS
CREATE POLICY "Active members directory readable by all authenticated"
ON public.members FOR SELECT USING (status != 'REMOVED' OR public.is_admin());

CREATE POLICY "Admins can insert or update members"
ON public.members FOR ALL USING (public.is_admin());

-- 3. Daily Links RLS
CREATE POLICY "Daily links viewable by active members"
ON public.daily_links FOR SELECT USING (true);

CREATE POLICY "Members can submit their own daily link"
ON public.daily_links FOR INSERT WITH CHECK (
    auth.uid() IN (SELECT user_id FROM public.members WHERE id = member_id)
    OR public.is_admin()
);

CREATE POLICY "Admins can modify all daily links"
ON public.daily_links FOR ALL USING (public.is_admin());

-- 4. Support Records RLS
CREATE POLICY "Support records viewable by members"
ON public.support_records FOR SELECT USING (true);

CREATE POLICY "Members can mark own support"
ON public.support_records FOR INSERT WITH CHECK (
    auth.uid() IN (SELECT user_id FROM public.members WHERE id = supporter_member_id)
    OR public.is_admin()
);

-- 5. Notices, Ads, Sponsors (Public read, admin write)
CREATE POLICY "Public read notices" ON public.notices FOR SELECT USING (is_active = true OR public.is_admin());
CREATE POLICY "Admin write notices" ON public.notices FOR ALL USING (public.is_admin());

CREATE POLICY "Public read ads" ON public.advertisements FOR SELECT USING (status = 'ACTIVE' OR public.is_admin());
CREATE POLICY "Admin write ads" ON public.advertisements FOR ALL USING (public.is_admin());

CREATE POLICY "Public read sponsors" ON public.sponsors FOR SELECT USING (status = 'ACTIVE' OR public.is_admin());
CREATE POLICY "Admin write sponsors" ON public.sponsors FOR ALL USING (public.is_admin());

-- 6. Audit logs (Admin only)
CREATE POLICY "Admin view audit logs" ON public.audit_logs FOR SELECT USING (public.is_admin());
CREATE POLICY "Admin insert audit logs" ON public.audit_logs FOR INSERT WITH CHECK (public.is_admin());

